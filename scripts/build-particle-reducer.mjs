import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// Compiles the particle reducer and embeds it, so the package needs no wasm asset at runtime.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'assembly/particle-reducer.ts');
const wasm = path.join(root, 'build/shado-particle-reducer.wasm');
const output = path.join(root, 'src/render/wasm/shado-particle-reducer-b64.ts');
const compiler = path.join(root, 'node_modules/.bin/asc');
mkdirSync(path.dirname(wasm), { recursive: true });
const result = spawnSync(compiler, [
  source,
  '--outFile', wasm,
  '--optimize',
  '--runtime', 'stub',
  '--enable', 'simd',
  '--noAssert',
], { stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status ?? 1);
writeFileSync(
  output,
  `// Generated by scripts/build-particle-reducer.mjs.\n` +
    `export const SHADO_PARTICLE_REDUCER_WASM_BASE64 = '${readFileSync(wasm).toString('base64')}';\n`
);
