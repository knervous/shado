import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'assembly/sprite-2d-motion-kernel.ts');
const wasm = path.join(root, 'build/sprite-2d-motion-kernel-simd.wasm');
const output = path.join(root, 'src/render/wasm/sprite-2d-motion-kernel-simd-b64.ts');
const compiler = path.join(root, 'node_modules/.bin/asc');
const result = spawnSync(compiler, [
  source,
  '--outFile', wasm,
  '--optimize',
  '--runtime', 'stub',
  '--enable', 'simd',
  '--noAssert',
], { stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status ?? 1);
writeFileSync(
  output,
  `// Generated by scripts/build-sprite-2d-motion-kernel.mjs.\n` +
    `export const SPRITE_2D_MOTION_KERNEL_SIMD_BASE64 = '${readFileSync(wasm).toString('base64')}';\n`
);
