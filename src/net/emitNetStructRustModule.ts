/** Same naming rule as the TypeScript emitter: projections are named after their owner field. */
function nestedName(fieldName: string, struct: NetStructLayout, owner: string): string {
  return struct.projectionOf ? `${owner}${capitalize(fieldName)}` : struct.name;
}

/** Rust type of one field in the borrowed writer struct `Name<'a>`, before `Option`. */
function messageFieldType(layout: NetStructLayout, field: NetFieldLayout, owner: string): string {
  if (field.kind === 'var') {
    if (field.varKind === 'str') return `&'a str`;
    if (field.varKind === 'bytes') return `&'a [u8]`;
    if (field.varKind === 'strList') return `&'a [&'a str]`;
    if (field.varKind === 'scalarList') return `&'a [${rustScalar(field.element!)}]`;
    return `&'a [${recordType(field.name, field.struct!, owner)}]`;
  }
  if (field.kind === 'struct') {
    const base = recordType(field.name, field.struct, owner);
    return field.count === 1 ? base : `[${base}; ${field.count}]`;
  }
  const base = scalarValueType(layout, field, owner);
  return field.count === 1 ? base : `[${base}; ${field.count}]`;
}

function messageFieldDefault(
  layout: NetStructLayout,
  field: NetFieldLayout,
  owner: string
): string {
  if (field.optional) return 'None';
  if (field.kind === 'var') return field.varKind === 'str' ? '""' : '&[]';
  return fixedFieldDefault(layout, field, owner);
}

/** `Name` for fixed records, `Name<'a>` for records that borrow heap data. */
function recordType(fieldName: string, struct: NetStructLayout, owner: string): string {
  const name = nestedName(fieldName, struct, owner);
  return struct.variable ? `${name}<'a>` : name;
}

function viewType(fieldName: string, struct: NetStructLayout, owner: string): string {
  return `${nestedName(fieldName, struct, owner)}View<'a>`;
}

/** The list element a reader sees: fixed records by value, variable ones as views. */
function elementType(fieldName: string, struct: NetStructLayout, owner: string): string {
  return struct.variable
    ? viewType(fieldName, struct, owner)
    : nestedName(fieldName, struct, owner);
}

function emitMessageWrite(field: NetFieldLayout, value: string): string {
  const slot = `at + ${field.byteOffset}`;
  if (field.kind === 'scalar') {
    if (field.count === 1) return scalarWriteStatement(field, 'buf', slot, value);
    return `for (i, value) in ${value}.iter().enumerate() {
    put_${field.type}(buf, ${slot} + i * ${scalarByteSize(field.type)}, *value);
}`;
  }
  if (field.kind === 'struct') {
    const stride = field.struct.stride;
    const write = (item: string, offset: string) =>
      field.struct.variable
        ? `${item}.write_message(buf, ${offset}, heap, cursor);`
        : `${item}.write_record(&mut buf[${offset}..${offset} + ${stride}]);`;
    if (field.count === 1) return write(value, slot);
    return `for (i, item) in ${value}.iter().enumerate() {
    ${write('item', `${slot} + i * ${stride}`)}
}`;
  }
  return emitVarMessageWrite(field, value, slot);
}

function emitVarMessageWrite(field: NetVarFieldLayout, value: string, slot: string): string {
  if (field.varKind === 'str' || field.varKind === 'bytes') {
    const bytes = field.varKind === 'str' ? `${value}.as_bytes()` : value;
    return `{
    let bytes = ${bytes};
    let to = net_reserve(buf, ${slot}, heap, cursor, bytes.len(), 1, 1);
    buf[to..to + bytes.len()].copy_from_slice(bytes);
}`;
  }
  if (field.varKind === 'strList') {
    return `{
    let to = net_reserve(buf, ${slot}, heap, cursor, ${value}.len(), 8, 4);
    for (i, text) in ${value}.iter().enumerate() {
        let bytes = text.as_bytes();
        let text_at = net_reserve(buf, to + i * 8, heap, cursor, bytes.len(), 1, 1);
        buf[text_at..text_at + bytes.len()].copy_from_slice(bytes);
    }
}`;
  }
  if (field.varKind === 'scalarList') {
    const size = field.elementSize;
    return `{
    let to = net_reserve(buf, ${slot}, heap, cursor, ${value}.len(), ${size}, ${size});
    for (i, value) in ${value}.iter().enumerate() {
        put_${field.element}(buf, to + i * ${size}, *value);
    }
}`;
  }
  const struct = field.struct!;
  const stride = struct.stride;
  const write = struct.variable
    ? `item.write_message(buf, to + i * ${stride}, heap, cursor);`
    : `item.write_record(&mut buf[to + i * ${stride}..to + (i + 1) * ${stride}]);`;
  return `{
    let to = net_reserve(buf, ${slot}, heap, cursor, ${value}.len(), ${stride}, ${struct.alignment});
    for (i, item) in ${value}.iter().enumerate() {
        ${write}
    }
}`;
}

/** Heap bytes, in exactly the order `write_message` reserves them. */
function emitMessageMeasure(field: NetFieldLayout): string[] {
  const steps = messageMeasureSteps(
    field,
    field.optional ? 'value' : `self.${rustIdent(field.name)}`
  );
  if (!steps.length || !field.optional) return steps;
  return [
    `if let Some(value) = self.${rustIdent(field.name)} {
${steps.map(step => indent(step, 4)).join('\n')}
}`,
  ];
}

function messageMeasureSteps(field: NetFieldLayout, value: string): string[] {
  if (field.kind === 'scalar') return [];
  if (field.kind === 'struct') {
    if (!field.struct.variable) return [];
    if (field.count === 1) return [`cursor = ${value}.measure(cursor);`];
    return [`for item in ${value}.iter() {\n    cursor = item.measure(cursor);\n}`];
  }
  if (field.varKind === 'str' || field.varKind === 'bytes') {
    return [`cursor = net_measure(cursor, ${value}.len(), 1, 1);`];
  }
  if (field.varKind === 'strList') {
    return [
      `cursor = net_measure(cursor, ${value}.len(), 8, 4);`,
      `for text in ${value}.iter() {\n    cursor = net_measure(cursor, text.len(), 1, 1);\n}`,
    ];
  }
  if (field.varKind === 'scalarList') {
    return [
      `cursor = net_measure(cursor, ${value}.len(), ${field.elementSize}, ${field.elementSize});`,
    ];
  }
  const struct = field.struct!;
  const reserve = `cursor = net_measure(cursor, ${value}.len(), ${struct.stride}, ${struct.alignment});`;
  if (!struct.variable) return [reserve];
  return [reserve, `for item in ${value}.iter() {\n    cursor = item.measure(cursor);\n}`];
}

function emitViewAccessor(layout: NetStructLayout, field: NetFieldLayout, owner: string): string {
  const name = rustIdent(field.name);
  const [type, body] = viewAccessorParts(layout, field, owner);
  if (field.presenceBit === undefined) {
    return `pub fn ${name}(&self) -> ${type} {
${indent(body, 4)}
}`;
  }
  return `pub fn ${name}(&self) -> Option<${type}> {
    if !net_has_presence(self.record, ${field.presenceBit}) {
        return None;
    }
    Some({
${indent(body, 8)}
    })
}`;
}

function viewAccessorParts(
  layout: NetStructLayout,
  field: NetFieldLayout,
  owner: string
): [type: string, body: string] {
  const offset = field.byteOffset;
  if (field.kind === 'scalar') {
    if (field.count === 1) {
      return [
        scalarValueType(layout, field, owner),
        scalarReadExpression(layout, field, owner, 'self.record', String(offset)),
      ];
    }
    return [
      `[${rustScalar(field.type)}; ${field.count}]`,
      `core::array::from_fn(|i| get_${field.type}(self.record, ${offset} + i * ${scalarByteSize(field.type)}))`,
    ];
  }
  if (field.kind === 'struct') {
    const stride = field.struct.stride;
    const type = elementType(field.name, field.struct, owner);
    const read = (at: string) =>
      field.struct.variable
        ? `${nestedName(field.name, field.struct, owner)}View::from_parts(&self.record[${at}..${at} + ${stride}], self.heap)`
        : `${type}::read_record(&self.record[${at}..${at} + ${stride}])`;
    if (field.count === 1) return [type, read(String(offset))];
    return [
      `[${type}; ${field.count}]`,
      `core::array::from_fn(|i| {
    let at = ${offset} + i * ${stride};
    ${read('at')}
})`,
    ];
  }
  if (field.varKind === 'str') {
    return [`&'a str`, `net_heap_str(self.record, ${offset}, self.heap)`];
  }
  if (field.varKind === 'bytes') {
    return [`&'a [u8]`, `net_heap_bytes(self.record, ${offset}, self.heap)`];
  }
  const element =
    field.varKind === 'strList'
      ? `&'a str`
      : field.varKind === 'scalarList'
        ? rustScalar(field.element!)
        : elementType(field.name, field.struct!, owner);
  return [`NetList<'a, ${element}>`, `net_list(self.record, ${offset}, self.heap)`];
}

/**
 * Every heap reference is checked, present or not: an honest writer leaves an
 * absent field zeroed, which always passes.
 */
function emitViewValidate(field: NetFieldLayout, owner: string): string[] {
  const offset = field.byteOffset;
  if (field.kind === 'scalar') return [];
  if (field.kind === 'struct') {
    if (!field.struct.variable) return [];
    const view = `${nestedName(field.name, field.struct, owner)}View`;
    const stride = field.struct.stride;
    if (field.count === 1) {
      return [`${view}::validate(&record[${offset}..${offset + stride}], heap, budget)?;`];
    }
    return [
      `for i in 0..${field.count} {
    let at = ${offset} + i * ${stride};
    ${view}::validate(&record[at..at + ${stride}], heap, budget)?;
}`,
    ];
  }
  if (field.varKind === 'str') {
    return [
      `{
    let (start, len) = net_validate_slot(record, ${offset}, heap, 1, budget)?;
    core::str::from_utf8(&heap[start..start + len]).map_err(|_| NetDecodeError::InvalidUtf8)?;
}`,
    ];
  }
  if (field.varKind === 'strList') {
    return [
      `{
    let (start, len) = net_validate_slot(record, ${offset}, heap, 8, budget)?;
    for i in 0..len {
        let (text, text_len) = net_validate_slot(heap, start + i * 8, heap, 1, budget)?;
        core::str::from_utf8(&heap[text..text + text_len]).map_err(|_| NetDecodeError::InvalidUtf8)?;
    }
}`,
    ];
  }
  if (field.varKind !== 'structList' || !field.struct!.variable) {
    return [`net_validate_slot(record, ${offset}, heap, ${field.elementSize}, budget)?;`];
  }
  const struct = field.struct!;
  const view = `${nestedName(field.name, struct, owner)}View`;
  return [
    `{
    let (start, len) = net_validate_slot(record, ${offset}, heap, ${struct.stride}, budget)?;
    for i in 0..len {
        let at = start + i * ${struct.stride};
        ${view}::validate(&heap[at..at + ${struct.stride}], heap, budget)?;
    }
}`,
  ];
}

